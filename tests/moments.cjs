const assert = require('node:assert/strict');
const { chromium } = require(process.env.DASHBOARD_TEST_PLAYWRIGHT || 'playwright');
const { startTestServer } = require('./browser-server.cjs');

(async () => {
  const fixture = await startTestServer();
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] }).catch(async error => {
    await fixture.close();
    throw error;
  });
  try {
    const desktop = await browser.newPage();
    const phone = await browser.newPage({ viewport: { width: 360, height: 740 }, isMobile: true, hasTouch: true });
    const password = 'fixture-unlock-2026';
    const title = '模拟纪念日';
    const body = '一起经历的一段测试记录';
    const detail = '想记住的测试细节';
    const errors = [];
    for (const page of [desktop, phone]) page.on('pageerror', error => errors.push(error.message));
    const idle = page => page.waitForFunction(() => syncClient?.ready && !syncClient.localWrites && !syncClient.localRunning);
    await desktop.goto(fixture.url);
    await idle(desktop);
    await desktop.locator('#nav [data-view=moments]').click();
    await desktop.locator('#momentUnlock input[name=password]').fill(password);
    await desktop.locator('#momentUnlock input[name=confirmation]').fill(password);
    await desktop.locator('#momentUnlock button').click();
    await desktop.locator('#momentList').waitFor();
    await desktop.locator('.moment-hero [data-moment-new]').click();
    const editor = desktop.locator('#momentEditor');
    assert.equal(await editor.locator('[name=kind]').count(), 0);
    await editor.locator('[name=date]').fill('2026-10-17');
    await editor.locator('[name=title]').fill(title);
    await editor.locator('[name=body]').fill(body);
    await editor.locator('[name=tags]').fill('纪念，旅行');
    await editor.locator('[name=tags]').press('Enter');
    assert.equal(await editor.locator('[data-remove-tag]').count(), 2);
    await editor.locator('[name=favorite]').check();
    const photo = await desktop.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = 32;
      canvas.height = 24;
      const context = canvas.getContext('2d');
      context.fillStyle = '#eaacb2';
      context.fillRect(0, 0, 32, 24);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    await editor.locator('[name=photo]').setInputFiles({ name: 'fixture.png', mimeType: 'image/png', buffer: Buffer.from(photo, 'base64') });
    await editor.locator('.moment-photo-preview img').waitFor();
    await editor.locator('button[type=submit]').click();
    await desktop.locator('.moment-card img').waitFor();
    assert(await desktop.locator('.moment-card').textContent().then(text => text.includes(title) && text.includes('纪念')));
    await desktop.locator('.moment-hero [data-moment-new]').click();
    await editor.locator('[name=body]').fill(detail);
    await editor.locator('[name=tags]').fill('纪');
    assert.equal(await editor.locator('[data-add-tag]').count(), 1);
    await editor.locator('[data-add-tag="纪念"]').click();
    await editor.locator('[data-add-tag="旅行"]').click();
    await editor.locator('[data-remove-tag="旅行"]').click();
    assert.equal(await editor.locator('[data-remove-tag]').count(), 1);
    await editor.locator('[name=tags]').fill('喜好');
    await editor.locator('button[type=submit]').click();
    await desktop.waitForFunction(() => document.querySelectorAll('.moment-card').length === 2);
    assert.equal(await desktop.locator('.moment-category,[data-moment-filter=detail]').count(), 0);
    await desktop.locator('#momentTagFilter').selectOption('纪念');
    assert.equal(await desktop.locator('.moment-card').count(), 2);
    await desktop.locator('#momentTagFilter').selectOption('喜好');
    assert.equal(await desktop.locator('.moment-card').count(), 1);
    assert.match(await desktop.locator('.moment-card').textContent(), new RegExp(detail));
    await desktop.locator('#momentTagFilter').selectOption('');
    await desktop.locator('[data-moment-filter=favorite]').click();
    assert.equal(await desktop.locator('.moment-card').count(), 1);
    await desktop.locator('#momentSearch').fill('旅行');
    assert.equal(await desktop.locator('.moment-card').count(), 1);
    await desktop.locator('#momentSearch').fill('not found');
    assert.equal(await desktop.locator('.moment-card').count(), 0);
    await desktop.locator('#momentRandom').click();
    assert.equal(await desktop.locator('#modalTitle').textContent(), title);
    await desktop.locator('#modalClose').click();
    const snapshot = await desktop.evaluate(() => JSON.stringify(syncClient.exportData()));
    for (const secret of [password, title, body, detail, '纪念', '旅行', '喜好', 'data:image/jpeg']) assert(!snapshot.includes(secret));
    await idle(desktop);
    await phone.goto(fixture.url);
    await idle(phone);
    await phone.locator('#bottomNav [data-view=moments]').click();
    assert.equal(await phone.locator('#momentUnlock').getAttribute('data-setup'), 'false');
    await phone.locator('#momentUnlock input[name=password]').fill('wrong');
    await phone.locator('#momentUnlock button').click();
    await phone.locator('#momentUnlock .moment-error').waitFor();
    assert.equal(await phone.locator('.moment-card').count(), 0);
    await phone.locator('#momentUnlock input[name=password]').fill(password);
    await phone.locator('#momentUnlock button').click();
    await phone.waitForFunction(() => document.querySelectorAll('.moment-card').length === 2);
    assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await phone.locator('.moment-card').filter({ hasText: title }).click();
    await phone.locator('#momentEdit').click();
    await phone.locator('#momentEditor [data-add-tag="喜好"]').click();
    await phone.locator('#momentEditor [name=body]').fill('修改后的测试内容');
    await phone.locator('#momentEditor button[type=submit]').click();
    await phone.waitForFunction(() => document.querySelector('.modal-overlay').hidden);
    await phone.locator('.moment-card').filter({ hasText: title }).click();
    await phone.locator('#modalClose').click();
    assert.equal(await phone.locator('#modalBody').textContent(), '');
    await phone.locator('#bottomNav [data-view=finance]').click();
    await phone.locator('#bottomNav [data-view=moments]').click();
    assert.equal(await phone.locator('.moment-card').count(), 0);
    assert.equal(await phone.locator('#momentUnlock').count(), 1);
    await phone.reload();
    await idle(phone);
    await phone.locator('#bottomNav [data-view=moments]').click();
    await phone.locator('#momentUnlock input[name=password]').fill(password);
    await phone.locator('#momentUnlock button').click();
    await phone.locator('.moment-card').filter({ hasText: '修改后的测试内容' }).waitFor();
    await phone.locator('#momentTagFilter').selectOption('喜好');
    assert.equal(await phone.locator('.moment-card').count(), 2);
    assert.deepEqual(errors, []);
    console.log('PASS moments password, encrypted backup, photos, tag creation, reuse, filters, editing, and locking');
  } finally {
    await browser.close();
    await fixture.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
