const assert = require('node:assert/strict');
const { chromium } = require(process.env.DASHBOARD_TEST_PLAYWRIGHT || 'playwright');
const { startTestServer } = require('./browser-server.cjs');

(async () => {
  const fixture = await startTestServer();
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] }).catch(async error => {
    await fixture.close();
    throw error;
  });
  try {
    const desktop = await browser.newPage({ timezoneId: 'Asia/Shanghai' });
    const phone = await browser.newPage({ viewport: { width: 360, height: 740 }, isMobile: true, hasTouch: true, timezoneId: 'Asia/Shanghai' });
    const password = 'fixture-unlock-2026';
    const title = '模拟纪念日';
    const body = '一起经历的一段测试记录';
    const detail = '想记住的测试细节';
    const recent = '本月的模拟记录';
    const earlierDay = '2026-10-17';
    const recentDay = '2026-11-02';
    const today = '2026-11-20';
    const errors = [];
    for (const page of [desktop, phone]) {
      page.on('pageerror', error => errors.push(error.message));
      await page.clock.setFixedTime(new Date('2026-11-20T12:00:00+08:00'));
    }
    const idle = page => page.waitForFunction(() => syncClient?.ready && !syncClient.localWrites && !syncClient.localRunning);
    const day = (page, date) => page.locator(`[data-moment-day="${date}"]`);
    const marks = page => page.locator('.moment-day.has-records');
    const waitCount = (page, date, count) => page.locator(`[data-moment-day="${date}"][data-moment-count="${count}"]`).waitFor();
    const edit = page => page.locator('#momentEditor');
    const close = page => page.locator('#modalClose').click();

    await desktop.goto(fixture.url);
    await idle(desktop);
    await desktop.locator('#nav [data-view=moments]').click();
    await desktop.locator('#momentUnlock input[name=password]').fill(password);
    await desktop.locator('#momentUnlock input[name=confirmation]').fill(password);
    await desktop.locator('#momentUnlock button').click();
    await day(desktop, today).waitFor();
    assert.equal(await day(desktop, today).getAttribute('aria-current'), 'date');
    assert.equal(await desktop.locator('.moment-calendar-grid > :first-child').getAttribute('aria-hidden'), 'true');
    await desktop.locator('#momentPrevMonth').click();
    await day(desktop, earlierDay).click();
    const editor = edit(desktop);
    assert.equal(await editor.locator('[name=date]').inputValue(), earlierDay);
    assert.equal(await editor.locator('[name=kind]').count(), 0);
    await editor.locator('[name=title]').fill(title);
    await editor.locator('[name=body]').fill(body);
    await editor.locator('[name=tags]').fill('纪念，旅行');
    await editor.locator('[name=tags]').press('Enter');
    assert.equal(await editor.locator('[data-remove-tag]').count(), 2);
    await editor.locator('[name=favorite]').check();
    const photo = await desktop.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = 32;
      canvas.height = 24;
      const context = canvas.getContext('2d');
      context.fillStyle = '#eaacb2';
      context.fillRect(0, 0, 32, 24);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    await editor.locator('[name=photo]').setInputFiles({ name: 'fixture.png', mimeType: 'image/png', buffer: Buffer.from(photo, 'base64') });
    await editor.locator('.moment-photo-preview img').waitFor();
    await editor.locator('button[type=submit]').click();
    await waitCount(desktop, earlierDay, 1);
    assert.equal(await day(desktop, earlierDay).locator('.moment-day-star').count(), 1);
    assert.equal(await desktop.locator('#view-moments').getByText(title, { exact: true }).count(), 0);

    await day(desktop, earlierDay).click();
    await desktop.locator('.moment-detail-photo').waitFor();
    assert.equal(await desktop.locator('#modalTitle').textContent(), title);
    assert.match(await desktop.locator('#modalBody').textContent(), /纪念/);
    await desktop.clock.setFixedTime(new Date('2026-11-20T13:00:00+08:00'));
    await desktop.locator('#momentAddOnDay').click();
    assert.equal(await editor.locator('[name=date]').inputValue(), earlierDay);
    await editor.locator('[name=body]').fill(detail);
    await editor.locator('[name=tags]').fill('纪');
    assert.equal(await editor.locator('[data-add-tag]').count(), 1);
    await editor.locator('[data-add-tag="纪念"]').click();
    await editor.locator('[data-add-tag="旅行"]').click();
    await editor.locator('[data-remove-tag="旅行"]').click();
    assert.equal(await editor.locator('[data-remove-tag]').count(), 1);
    await editor.locator('[name=tags]').fill('喜好');
    await editor.locator('button[type=submit]').click();
    await waitCount(desktop, earlierDay, 2);
    await day(desktop, earlierDay).click();
    assert.match(await desktop.locator('.moment-body').textContent(), new RegExp(detail));
    await desktop.locator('#momentNextNote').click();
    assert.equal(await desktop.locator('#modalTitle').textContent(), title);
    assert(await desktop.locator('#momentNextNote').isDisabled());
    await desktop.locator('#momentPrevNote').click();
    assert.match(await desktop.locator('.moment-body').textContent(), new RegExp(detail));
    await close(desktop);

    await desktop.locator('#momentToday').click();
    assert.equal(await desktop.locator('#momentMonthLabel').textContent(), '2026 年 11 月');
    await day(desktop, recentDay).click();
    await editor.locator('[name=body]').fill(recent);
    await editor.locator('button[type=submit]').click();
    await waitCount(desktop, recentDay, 1);
    await desktop.locator('#momentTagFilter').selectOption('喜好');
    await waitCount(desktop, earlierDay, 1);
    assert.equal(await marks(desktop).count(), 1);
    await day(desktop, earlierDay).click();
    assert.match(await desktop.locator('.moment-body').textContent(), new RegExp(detail));
    assert.equal(await desktop.locator('#momentNextNote').count(), 0);
    await close(desktop);
    await desktop.locator('#momentClearFilters').click();
    await waitCount(desktop, earlierDay, 2);
    await desktop.locator('[data-moment-filter=favorite]').click();
    await waitCount(desktop, earlierDay, 1);
    await desktop.locator('#momentSearch').fill('旅行');
    assert.equal(await marks(desktop).count(), 1);
    await desktop.locator('#momentSearch').fill('no matches');
    assert.equal(await marks(desktop).count(), 0);
    await desktop.locator('#momentClearFilters').click();
    await desktop.locator('#momentMonthJump').selectOption('2026-11');
    await waitCount(desktop, recentDay, 1);
    await desktop.locator('#momentSearch').fill(title);
    await waitCount(desktop, earlierDay, 1);
    await desktop.locator('#momentClearFilters').click();
    await desktop.locator('#momentRandom').click();
    assert(await desktop.locator('.moment-body').isVisible());
    await close(desktop);
    const snapshot = await desktop.evaluate(() => JSON.stringify(syncClient.exportData()));
    for (const secret of [password, title, body, detail, recent, '纪念', '旅行', '喜好', 'data:image/jpeg']) assert(!snapshot.includes(secret));
    await idle(desktop);

    await phone.goto(fixture.url);
    await idle(phone);
    await phone.locator('#bottomNav [data-view=moments]').click();
    assert.equal(await phone.locator('#momentUnlock').getAttribute('data-setup'), 'false');
    await phone.locator('#momentUnlock input[name=password]').fill('wrong');
    await phone.locator('#momentUnlock button').click();
    await phone.locator('#momentUnlock .moment-error').waitFor();
    assert.equal(await phone.locator('#momentCalendarGrid').count(), 0);
    await phone.locator('#momentUnlock input[name=password]').fill(password);
    await phone.locator('#momentUnlock button').click();
    await waitCount(phone, recentDay, 1);
    assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await phone.locator('#momentMonthJump').selectOption('2026-10');
    await waitCount(phone, earlierDay, 2);
    await day(phone, earlierDay).tap();
    await phone.locator('#momentNextNote').tap();
    await phone.locator('#momentEdit').tap();
    await edit(phone).locator('[data-add-tag="喜好"]').click();
    await edit(phone).locator('[name=body]').fill('修改后的测试内容');
    await phone.locator('#modalOverlay').tap({ position: { x: 4, y: 4 } });
    assert(await edit(phone).isVisible());
    assert.equal(await edit(phone).locator('[name=body]').inputValue(), '修改后的测试内容');
    await edit(phone).locator('button[type=submit]').click();
    await phone.locator('#modalOverlay').waitFor({ state: 'hidden' });
    await phone.locator('#bottomNav [data-view=finance]').click();
    await phone.locator('#bottomNav [data-view=moments]').click();
    assert.equal(await phone.locator('#momentCalendarGrid').count(), 0);
    assert.equal(await phone.locator('#momentUnlock').count(), 1);
    await phone.reload();
    await idle(phone);
    await phone.locator('#bottomNav [data-view=moments]').click();
    await phone.locator('#momentUnlock input[name=password]').fill(password);
    await phone.locator('#momentUnlock button').click();
    await waitCount(phone, recentDay, 1);
    await phone.locator('#momentTagFilter').selectOption('喜好');
    await waitCount(phone, earlierDay, 2);
    await day(phone, earlierDay).tap();
    await phone.locator('#momentNextNote').tap();
    assert.equal(await phone.locator('.moment-body').textContent(), '修改后的测试内容');
    await close(phone);
    assert.equal(await phone.locator('#modalBody').textContent(), '');
    assert.deepEqual(errors, []);
    console.log('PASS Moments calendar, marked and empty dates, same-day navigation, cross-month search, tag reuse, encrypted backup, and mobile editing');
  } finally {
    await browser.close();
    await fixture.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
